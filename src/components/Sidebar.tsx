// ============================================================================
// Role Badge Colors
// ============================================================================

const ROLE_BADGE_COLORS: Record<UserRole, string> = {
  admin: 'bg-red-500',
  analyst: 'bg-blue-500',
  ic_member: 'bg-purple-500',
  gov_partner: 'bg-green-500',
  epc: 'bg-yellow-500',
  investor: 'bg-teal-500',
};

// ============================================================================
// Sidebar Component
// ============================================================================

interface SidebarProps {
  userRole?: UserRole;
}

export default function Sidebar({ userRole }: SidebarProps) {
  const pathname = usePathname();
  const { logout, user } = useAuth();

  // Filter navigation items based on user role
  const visibleNavigation = useMemo(() => {
    // If using Supabase (no RBAC yet), show all items
    if (AUTH_PROVIDER !== 'azure_b2c' || !userRole) {
      return navigation;
    }

    return navigation.filter((item) => {
      // Dashboard is always visible
      if (!item.requiredPermissions) return true;

      // Check if user has any of the required permissions
      return checkAnyPermission(userRole, item.requiredPermissions);
    });
  }, [userRole]);

  // Get role display info
  const roleInfo = userRole ? USER_ROLES[userRole] : null;

  return (
    <div className="flex flex-col w-64 bg-gray-900 min-h-screen">
      {/* Header */}
      <div className="flex items-center justify-center h-16 bg-gray-800">
        <span className="text-white text-xl font-bold">AIP Platform</span>
      </div>

      {/* User Info (when using Azure AD B2C) */}
      {AUTH_PROVIDER === 'azure_b2c' && user && roleInfo && (
        <div className="px-4 py-3 border-b border-gray-800">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-full bg-gray-700 flex items-center justify-center">
              <span className="text-white font-medium">
                {user.email?.charAt(0).toUpperCase() || 'U'}
              </span>
            </div>
            <div className="flex-1 min-w-0">
              <div className="text-sm font-medium text-white truncate">
                {user.email}
              </div>
              <div className="flex items-center gap-2">
                <span className={`inline-flex items-center px-2 py-0.5 rounded text-xs font-medium text-white ${ROLE_BADGE_COLORS[userRole!]}`}>
                  {roleInfo.displayName}
                </span>
                {roleInfo.requiresMFA && (
                  <span title="MFA Required">
                    <ShieldCheckIcon className="w-3.5 h-3.5 text-green-400" />
                  </span>
                )}
              </div>
            </div>
          </div>
        </div>
      )}

      {/* Navigation */}
      <nav className="flex-1 px-4 py-6 space-y-1 overflow-y-auto">
        {visibleNavigation.map((item) => {
          const isActive = pathname === item.href ||
            (item.href !== '/dashboard' && pathname.startsWith(item.href));
          return (
            <Link
              key={item.name}
              href={item.href}
              className={`flex items-center px-4 py-3 text-sm font-medium rounded-lg transition-colors ${
                isActive
                  ? 'bg-blue-600 text-white'
                  : 'text-gray-300 hover:bg-gray-800 hover:text-white'
              }`}
            >
              <item.icon className="w-5 h-5 mr-3" />
              {item.name}
              {item.adminOnly && (
                <span className="ml-auto">
                  <LockIcon className="w-3.5 h-3.5 text-gray-500" />
                </span>
              )}
            </Link>
          );
        })}
      </nav>

      {/* Sign Out */}
      <div className="px-4 py-4 border-t border-gray-800">
        <button
          onClick={logout}
          className="flex items-center w-full px-4 py-3 text-sm font-medium text-gray-300 rounded-lg hover:bg-gray-800 hover:text-white transition-colors"
        >
          <LogoutIcon className="w-5 h-5 mr-3" />
          Sign Out
        </button>
      </div>
    </div>
  );
}

